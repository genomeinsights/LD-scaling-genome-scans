    n_sub <- length(ORs)
    
    PR_data <- list()
    
    message("Getting PR from original ORs \n")
    for(sub in 1:n_sub){
      cat(paste0(round(sub/n_sub*100),"%"),"..")
      
      PR_data[[sub]] <- rbindlist(mclapply(1:nrow(ORs[[sub]]),function(x){
        get_PR_data(OR_data = ORs[[sub]][x],SNP_res=data$SNP_res,ld_test_th=ld_test_th,d_test_th=d_test_th,p_Va_th=p_Va_th)  
      },mc.cores = cores))  
      
    }
    
    PR_data <- rbindlist(PR_data)
    
    ## now get ORs based on C-values (replacing l_min, rho_w and alpha)
    message("Getting PR from C-scores")
    
    C_vals <- data$SNP_res[1:.N,grep("C_",colnames(data$SNP_res)),with = FALSE]
    
    ORs <- get_ORs_from_C(GTs=data$GTs,
                          map=data$SNP_res,
                          C_vals=C_vals,
                          decay_tbl = data$decay_tbl,
                          rho_ld_lim = list(min=0.5, max=1.0),
                          rho_d_lim = list(min=0.90, max=1.0),
                          tau_C_lim = list(min=1e-6, max=0.5),
                          n_cores=cores,
                          n_rep = n_rep_C)
    
    
    
    ORs <- split(ORs,rep(1:(nrow(ORs)/1000),each=1000))  
    n_sub <- length(ORs)
    
    ## PR from C-scores
    PR_data_C <- list()
    for(sub in 1:n_sub){
      cat(paste0(round(sub/n_sub*100),"%"),"..")
      
      PR_data_C[[sub]] <- rbindlist(mclapply(1:nrow(ORs[[sub]]),function(x){
        
        get_PR_data(OR_data = ORs[[sub]][x],SNP_res=data$SNP_res,ld_test_th=ld_test_th,d_test_th=d_test_th,p_Va_th=p_Va_th)  
        
      },mc.cores = cores))  
    }
    
    PR_data_C <- rbindlist(PR_data_C)
    
    ## save data in same folder with _PR suffix
    saveRDS(list(PR_data=PR_data,
                 PR_data_C=PR_data_C,
                 ORs=data$ORs_for_Cscore,
                 ORs_C=rbindlist(ORs)),
