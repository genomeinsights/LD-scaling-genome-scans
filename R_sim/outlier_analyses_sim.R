    PR_OGR <- readRDS(PR_file)
    PR_data <- rbindlist(list(PR_OGR$PR_data, PR_OGR$PR_data_C), fill = TRUE)
    
    data_path <- res_files[grep(paste0(base_name, "."), res_files, fixed = TRUE)][1]
    data <- readRDS(data_path)
    
    SNP_res <- data$SNP_res
    
    OR_focals <- PR_data$OR_focals
    lens <- lengths(OR_focals)
    
    # Map focal markers -> p_Va (list column aligned to OR_focals)
    pVa_vec <- SNP_res[match(unlist(OR_focals), marker), p_Va]
    pVa_list <- split(pVa_vec, rep(seq_along(OR_focals), times = lens))
    
    # ensure length alignment (including empty OR_focals)
    pVa_full <- vector("list", length(OR_focals))
    pVa_full[lens != 0L] <- pVa_list
    
    PR_data[, p_Va := pVa_full]
    
    # add scenario identifiers once
    meta <- SNP_res[1, .(c, V, rep)]
    
    all_draws[[PR_file]] <- cbind(meta, PR_data)
    
    # store all QTN p_Va for baseline distribution
    all_qtn[[PR_file]] <- cbind(
      meta,
      data.table(method = "all_QTN", p_Va = list(SNP_res[type == "QTN", p_Va]))
