### --- Get focal QNT for a given SNP --- ###
#   gds - gds file generated by SNPrelate
#   map - The corresponding map file that contains at least columns "marker" 
#     "and "type" where type=="QTN" are the potential focal QTN


focal_QTN <- function(gds,map){
  ids <- read_gds_ids(gds)
  rbindlist(
    lapply(unique(ids$snp_chr), function(ch) {
      
      # SNPs on this chromosome in the GDS
      idx_chr      <- which(ids$snp_chr == ch)
      snp_ids_chr  <- ids$snp_id[idx_chr]
      
      # All SNPs on this chromosome in the map
      map_chr      <- map[Chr == ch]
      markers_chr  <- map_chr$marker
      
      # QTNs on this chromosome
      qtn_chr      <- map_chr[type == "QTN", marker]
      
      # If no QTNs on this chromosome: everything is "not in LD"
      if (length(qtn_chr) == 0L) {
        return(data.table(
          Chr              = ch,
          marker           = markers_chr,
          max_LD_with_QTN  = 0,
          focal_QTN        = NA_character_,
          bp_to_focal_QTN  = NA_real_
        ))
      }
      
      # Full LD matrix (r^2) for this chromosome
      ld_obj  <- snpgdsLDMat(
        gds,
        snp.id     = snp_ids_chr,
        method     = "r",
        slide      = -1,
        num.thread = 8,
        verbose    = FALSE
      )
      LDmat <- ld_obj$LD^2
      dimnames(LDmat) <- list(snp_ids_chr, snp_ids_chr)
      
      # Sub-matrix: rows = QTNs, cols = all SNPs on this chromosome
      ld_sub <- LDmat[qtn_chr, markers_chr, drop = FALSE]
      
      # For each SNP (column), get max LD with any QTN and the QTN giving that max
      max_ld    <- apply(ld_sub, 2, max, na.rm = TRUE)
      focal_idx <- apply(ld_sub, 2, which.max)
      focal_qtn <- qtn_chr[focal_idx]
      
      # Position lookup (use 'Pos' or 'bp' depending on your map)
      pos_vec <- map_chr$Pos   # or map_chr$bp
      names(pos_vec) <- map_chr$marker
      
      bp_to_focal <- abs(pos_vec[markers_chr] - pos_vec[focal_qtn])
      
      data.table(
        Chr             = ch,
        marker          = markers_chr,
        max_LD_with_QTN = max_ld,
        focal_QTN       = focal_qtn,
        bp_to_focal_QTN = bp_to_focal
      )
    }),
    fill = TRUE
  )
}


### --- Extract PR from OR data --- ###
#   OR_data - data generated by function get_ORs_for_draw
#   SNP results (contains relevant q-values and F-values for outlier analyses)
#   ld_test_th - LD threshold defining true positive (in LD-decay units, rho)
#   d_test_th - distance threshold defining true positive (in LD-decay units, rho)
#   p_Va_th - Threshold for defining true positive focal QTn
###
get_PR_data <- function(OR_data,SNP_res,ld_test_th=0.75,d_test_th=0.95,p_Va_th=0.05){
  ors <- unlist(OR_data$ORs,recursive = FALSE)
  
  if(length(na.omit(ors))!=0){
    #or <- ors[[1]]
    OR_focals <- unlist(lapply(ors,function(or){
      
      unique(SNP_res[marker %in% or & 
                       rho_ld<ld_test_th & 
                       rho_d<d_test_th][which.min(rho_ld),focal_QTN])
      
    }))
    
    OR_focals <- unique(OR_focals)  
    
    true <- SNP_res[p_Va>p_Va_th,unique(focal_QTN)] 
    
    true_OR_focals <- OR_focals[OR_focals %in% true]
    
    TP <- length(true_OR_focals)
    FP <- length(ors) - TP
    FN <- length(which(!true %in% true_OR_focals))
    precision <- TP/(TP+FP)
    recall <- TP/(TP+FN)
    PR = precision*recall
    
    FP_ntrl <- sum(sapply(ors,function(or){
      length(SNP_res[marker %in% or & Chr_type=="ntrl",marker])>0
    }))
    
    return(data.table(OR_data[1,],
                      TP,
                      FP,
                      FN,
                      precision,
                      recall,
                      PR,
                      FP_ntrl,
                      OR_focals=list(OR_focals))) 
  }else{
    
    return(data.table(OR_data[1,],
                      TP=0,
                      FP=0,
                      FN=length(SNP_res[p_Va>p_Va_th,unique(focal_QTN)] ),
                      precision = 0,
                      recall = 0,
                      PR = 0,
                      FP_ntrl = 0,
                      OR_focals= list(NA)))
  }
}


### ---  Get oulier regions from C-scores --- ###
#   rho_ld_lim - ld threshold for defining ORs
#   rho_d_lim - d threshold for defining ORs
#   tau_C_lim - C-threshold for defining outlier SNPs
#   n_rep - number of draws
###

get_ORs_from_C <- function(GTs,
                           map,
                           C_vals,
                           decay_tbl, 
                           rho_ld_lim = list(min=0.5, max=1.0),
                           rho_d_lim = list(min=0.90, max=1.0),
                           tau_C_lim = list(min=1e-6, max=0.5),
                           n_cores=1,
                           n_rep=500
){
  
  ## create gds
  gds_path = tempfile(fileext = ".gds")
  gds <- create_gds_from_geno(geno = GTs, map=map,gds_path)
  on.exit({ snpgdsClose(gds); unlink(gds_path) }, add = TRUE) 
  
  
  ## get outliers
  C_vals <- as.matrix(C_vals)
  ids <- read_gds_ids(gds)
  
  ## Analyse only SNPs that have C>0 for any of the C-scores
  all_outliers <- ids$snp_id[apply(C_vals,1,max)>0]
  
  idx <- which(ids$snp_id %in% all_outliers)
  
  outl_chromosomes <- ids$snp_chr[idx]
  
  chrs <- unique(outl_chromosomes)
  
  ## get LD-edge list for each chromosome
  el_chr <- list()
  
  for(ch in chrs){
    outl_ch <- all_outliers[outl_chromosomes==ch]
    
    el_chr[[ch]] <- get_el(gds = gds,
                           idx =  which(ids$snp_id %in% outl_ch),
                           slide_win_ld = -1, ## user all pairwise comparisons
                           n_cores = n_cores)
  }
  
  el_chr <- rbindlist(el_chr)
  
  ## get ORs
  n_sub <- n_rep/500
  ORs <- list()
  
  for(sub in 1:n_sub){
    cat(paste0(sub/n_sub*100,"%"),"..")
    
    ORs[[sub]] <- rbindlist(mclapply(1:500,function(x){
      tau_C <- runif(1,tau_C_lim$min,tau_C_lim$max)
      rho_ld <- runif(1,rho_ld_lim$min,rho_ld_lim$max)
      rho_d <- runif(1,rho_d_lim$min,rho_d_lim$max)
      
      if(length(el_chr)>0){
        ## get thresholds based on drawn rho values
        d_th_by_chr <- setNames(as.integer(d_from_rho(decay_tbl$summary$a, rho_d)), decay_tbl$summary$Chr)
        ld_th_by_chr <- setNames(decay_tbl$summary$b + (1 - decay_tbl$summary$b) * (1 - rho_ld), decay_tbl$summary$Chr) 
        el_chr[,d_th:=d_th_by_chr[Chr1]]
        el_chr[,ld_th:=ld_th_by_chr[Chr1]]
      }
      
      if (length(el_chr) == 0){
        ORs <- data.table(method=colnames(C_vals),mean_d_th_OR=NA,mean_ld_th_OR=NA,ORs=list(NA))
      } else {
        
        ORs <- rbindlist(lapply(1:ncol(C_vals),function(i){
          
          outl_me <- ids$snp_id[C_vals[,i]>tau_C]
          
          ed <- el_chr[r2 > ld_th & d < d_th & SNP1 %in% outl_me & SNP2 %in% outl_me ,.(SNP1, SNP2)]
          
          if (nrow(ed) < 1){
            return(data.table(method=colnames(C_vals)[i],mean_d_th_OR=mean(el_chr$d_th),mean_ld_th_OR=mean(el_chr$d_th),ORs=list(NA)))
            next
          } 
          
          g <- graph_from_data_frame(ed, directed = FALSE)
          comps <- decompose(g)
          ors <- lapply(comps, function(cc) V(cc)$name)
          
          names(ors) <- seq_len(length(ors))
          
          return(data.table(method=colnames(C_vals)[i],mean_d_th_OR=mean(el_chr$d_th),mean_ld_th_OR=mean(el_chr$ld_th),ORs=list(ors)))
        }))
        
      }
      
      #Return draw
      cbind(tau_C=tau_C,rho_d=rho_d,rho_ld=rho_ld,ORs)
    },mc.cores=n_cores))
  }
  
  return(rbindlist(ORs))
}



### --- Get area under the PR curve (AUC-PR) --- ###
# PR_data generated by function get_PR_data (above)
# n1 and n2 are the number of bootstrap replicates to draw for a smooth AUC-curve
###
get_AUC_OR <- function(PR_data,params, n1=500, n2=500,cores=1){
  
  ## get running maximum
  
  cummax_PR <- rbindlist(mclapply(1:n1, function(x){
    rbindlist(lapply(PR_data[,unique(method)],function(meth){
      cbind(indx=1:n2,method=meth,PR_data[method==meth][sample(1:.N,n2,replace = TRUE),.(value=cummax(PR),rep=x)])    
    }))
  },mc.cores = cores))
  
  AUC_norm <- list()
  AUC <- list()
  
  ## get AUC for each method
  for(meth in cummax_PR[,unique(method)]){
    PR_star <- cummax_PR[ method==meth,mean(value),by=.(method,indx)][,V1]          
    k <- seq_along(PR_star)                    
    AUC_pracma <- trapz(k, PR_star)
    PR_star_max <- trapz(k, c(0,rep(1,(max(k)-1))))
    AUC_norm[[meth]] <- AUC_pracma / PR_star_max
    AUC[[meth]] <- AUC_pracma 
  }
  
  data_auc <- cbind(params,cummax_PR[,.(mean_PR=mean(value)),by=.(method,indx)])
  
  max_PR <- cummax_PR[,max(value),by=method]
  max_PR <- max_PR[match(names(AUC),max_PR$method),V1]
  AUC <- data.table(params, method=names(AUC),AUC=unlist(AUC),AUC_norm=unlist(AUC_norm),max_PR)
  
  return(list(data=data_auc,AUC=AUC))
}

