############################################################
##  Simulated data analyses: LD-scaled genome scans
##
##  This script performs the full downstream analysis and
##  benchmarking of simulated genomic data used in the study.
##
##  Overview:
##  - Input data consist of parsed simulation outputs with
##    genotypes for 500 individuals per replicate.
##  - A fixed subset of 125 individuals is selected to match
##    empirical sampling design and reduce computational load.
##
##  For each simulation replicate, the script:
##    1) Estimates chromosome-specific LD-decay curves
##    2) Performs genotype–environment association analyses
##       using EMMAX and LFMM
##    3) Applies LD-scaling to association statistics (F′)
##    4) Defines outlier regions (ORs) using single-linkage
##       clustering across thousands of random parameter draws
##    5) Integrates evidence across draws using consistency
##       scores (C)
##    6) Assigns focal QTNs to ORs based on LD and distance
##    7) Quantifies performance using OR-level precision,
##       recall, and AUC-based robustness metrics
##
##  Because the simulations have known ground truth (QTNs),
##  this framework allows direct classification of true and
##  false positive outlier regions and systematic benchmarking
##  of LD-scaled vs. SNP-level inference.
##
##  Output:
##  - Intermediate results are saved to ./results_sim/
##  - Aggregated performance metrics and summary tables are
##    saved to ./data/ and reused by plotting scripts
##
##  Notes:
##  - Core functions used here are shared with empirical
##    analyses and form the basis of the LDscanR package.
##  - Simulation-specific helper functions are defined locally
##    and are not part of the package API.
############################################################
## WARNING: This script is computationally intensive and
## intended to be run on a multicore system or HPC cluster.
## Enough example data in ./parsed_data/ (one simulation replicate) 
## for the code to work

